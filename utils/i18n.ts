const normalizeLocale = (locale?: string): SupportedLocale => {
  const value = locale?.toLowerCase() ?? "en";
  if (value.startsWith("ko")) return "ko";
  if (value.startsWith("ja")) return "ja";
  return "en";
};

let currentLocale: SupportedLocale = normalizeLocale(
  Localization.getLocales()?.[0]?.languageTag,
);

const listeners = new Set<(locale: SupportedLocale) => void>();
const STORAGE_KEY = "eerme.locale";
let hasHydrated = false;

export const getLocale = () => currentLocale;

export const getLocaleTag = () => localeTagMap[currentLocale];

export const setLocale = (next: SupportedLocale) => {
  currentLocale = next;
  listeners.forEach((listener) => listener(currentLocale));
  AsyncStorage.setItem(STORAGE_KEY, next).catch(() => undefined);
};

const hydrateLocale = async () => {
  if (hasHydrated) return;
  hasHydrated = true;
  try {
    const stored = await AsyncStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "ko" || stored === "ja") {
      setLocale(stored);
    }
  } catch {
    // noop
  }
};

export const useLocale = () => {
  const [locale, setLocaleState] = useState<SupportedLocale>(currentLocale);

  useEffect(() => {
    hydrateLocale();
    const handler = (next: SupportedLocale) => setLocaleState(next);
    listeners.add(handler);
    return () => {
      listeners.delete(handler);
    };
  }, []);

  return locale;
};

const interpolate = (value: string, params?: Record<string, string | number>) =>
  value.replace(/\{(\w+)\}/g, (_, key) => `${params?.[key] ?? ""}`);

export const t = (key: keyof typeof translations.en, params?: Record<string, string | number>) => {
  const value = translations[currentLocale][key] ?? translations.en[key];
  if (Array.isArray(value)) {
    return value.join(",");
  }
  return interpolate(value, params);
};

export const tList = (key: keyof typeof translations.en) => {
  const value = translations[currentLocale][key] ?? translations.en[key];
  return Array.isArray(value) ? value : [value];
};
